export function formatInr(amount) {
  if (amount == null || Number.isNaN(Number(amount))) return "—";
  return new Intl.NumberFormat("en-IN", {
    style: "currency",
    currency: "INR",
    maximumFractionDigits: 0,
  }).format(amount);
}

/** Compact INR for tight KPI tiles (e.g. ₹1.92 Cr). */
export function formatInrCompact(amount) {
  const n = Number(amount);
  if (amount == null || Number.isNaN(n)) return "—";
  if (Math.abs(n) >= 1e7) return `₹${(n / 1e7).toFixed(n % 1e7 === 0 ? 0 : 2)} Cr`;
  if (Math.abs(n) >= 1e5) return `₹${(n / 1e5).toFixed(n % 1e5 === 0 ? 0 : 1)} L`;
  return formatInr(n);
}

export function eventStatusLabel(status) {
  if (status === "completed") return "Conducted";
  if (status === "live") return "Live / ongoing";
  if (status === "upcoming") return "Upcoming";
  return status;
}
