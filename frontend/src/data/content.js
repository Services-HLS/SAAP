/** Map gallery thumbnail URL to full-resolution image on the SAAP CDN. */
export function photoFullUrl(url) {
  if (!url) return url;
  return url.replace("/Photoadd_ImgThumbnail/", "/Photoadd_Img/");
}

/** Same file uploaded twice under different names on the CDN. */
const PHOTO_DUPLICATE_FILES = new Set([
  "U10000500IMG2026100715570367979_AL77_DP.jpg",
]);

export function uniquePhotos(urls) {
  const seen = new Set();
  const out = [];
  for (const url of urls) {
    const file = url.split("/").pop();
    if (PHOTO_DUPLICATE_FILES.has(file) || seen.has(file)) continue;
    seen.add(file);
    out.push(url);
  }
  return out;
}

